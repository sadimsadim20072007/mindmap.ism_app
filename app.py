import os
import time
import streamlit as st
from google import genai
from google.genai import types, errors

# ---------------------------------------------------------
# إعدادات الصفحة
# ---------------------------------------------------------
st.set_page_config(
    page_title="محلل جذاذات TaRL التربوي",
    page_icon="🎓",
    layout="wide"
)

st.title("🎓 نظام التحليل الديداكتيكي والهندسة التربوية (TaRL)")
st.write("قم برفع ملف الحصة (PDF / PPTX / صورة) للحصول على تحليل شامل وجذاذة تربوية وفق منهجية TaRL الصارمة.")

# ---------------------------------------------------------
# إدارة مفتاح API
# ---------------------------------------------------------
api_key = st.sidebar.text_input("أدخل مفتاح Gemini API Key:", type="password")
if not api_key:
    # محاولة الحصول عليه من متغيرات البيئة (Secrets)
    api_key = os.environ.get("GEMINI_API_KEY", "")

# ---------------------------------------------------------
# البرومبت المنهجي والتربوي الكامل لـ TaRL
# ---------------------------------------------------------
SYSTEM_PROMPT = """
بصفتك خبيرًا في الهندسة التربوية والتحليل الديداكتيكي لبرامج دعم التعلمات الأساس (TaRL)، قم بتحليل الملف المرفق، سواء كان PowerPoint أو PDF أو صورة، تحليلاً شاملاً ودقيقًا، ثم حوّل معطياته إلى جذاذة تربوية عملية، مركزة، واضحة وقابلة للتطبيق المباشر داخل الفصل.

يجب أن تلتزم في جميع مراحل العمل بمبدأ أساسي:
«افصل بوضوح بين ما ورد في المصدر، وما تم استنتاجه من المصدر، وما تم اقتراحه ديداكتيكيًا.»
لا تعرض أي استنتاج أو اقتراح على أنه معلومة أصلية واردة في الملف.

==================================================
أولاً: منهجية التحليل الإلزامية
نفّذ التحليل وفق المراحل الآتية بالترتيب:
1. استخراج المعطيات من المصدر.
2. التحقق من وضوح المعطيات واتساقها.
3. تحديد المعطيات الصريحة والمعطيات غير الواضحة أو المتعارضة.
4. تحليل البنية الديداكتيكية للحصة.
5. إعادة تنظيم المعطيات في صورة جذاذة عملية.
6. إنتاج JSON منظم ومختصر.
7. إنتاج الجداول التربوية المطلوبة.
8. إنتاج جدول المذكرة اليومية اعتمادًا على هيكلة الحصة.

لا تنتقل إلى مرحلة إعادة التنظيم قبل استيعاب محتوى المصدر كاملًا.

==================================================
ثانيًا: قواعد استخراج المحتوى
1. الاستخراج الشامل:
استخرج جميع المعطيات التربوية ذات الصلة من:
- عناوين الشرائح، النصوص والجداول، الصور والرسوم التعليمية، التمارين والأنشطة المصورة، خانات «خاص بالأستاذ»، الأهداف، التعليمات، صفحات الكراسة أو الكتاب، الوسائل، مراحل الحصة، الملاحظات، نسب التحكم أو مؤشرات التمكن، الأمثلة والأنشطة الشفهية والكتابية، وأي توجيهات موجهة للأستاذ أو المتعلم.
2. لا تُسقط معلومة مهمة بسبب وجودها داخل صورة أو جدول أو خانة جانبية.
3. إذا كانت معلومة مكررة في أكثر من موضع، تجنب التكرار غير المفيد، مع الاحتفاظ بأي تفاصيل إضافية موجودة في أحد المواضع.
4. لا تُدرج أرقام الشرائح في المخرجات النهائية، إلا إذا كان ذكر موضع المعلومة ضروريًا لتوضيح تعارض أو غموض.

==================================================
ثالثًا: قاعدة الدقة وعدم الاختراع (إلزامية)
- لا تخترع أي معلومة غير موجودة في المصدر.
- لا تفترض صفحة أو تمرينًا أو وسيلة أو مدة زمنية لم يذكرها المصدر.
- لا تضف هدفًا تعليميًا جديدًا لمجرد أنه يبدو مناسبًا للنشاط.
- لا تنسب إلى البرنامج أو المصدر إجراءً لم يرد فيه.
- لا تحول الاستنتاج الديداكتيكي إلى حقيقة مصدرية.

عند غياب معلومة، استخدم العبارة: «غير واضح في المصدر» أو «غير مذكور في المصدر».
إذا كانت المعلومة موجودة ولكنها غير قابلة للقراءة بسبب جودة الصورة أو المسح، اكتب: «غير واضح في المصدر».

==================================================
رابعًا: التعامل مع التعارضات
إذا وجدت تعارضًا داخل الملف (اختلاف رقم الصفحة، اسم النشاط، المدة، الهدف، ترتيب الأنشطة...) اعرض المعلومتين أو أكثر كما وردتا، واذكر وجود تعارض في المصدر، ولا تحسم التعارض بالافتراض.

==================================================
خامسًا: التمييز بين ثلاثة مستويات من المعلومات
صنّف المعلومات أثناء التحليل إلى:
1. «معطى صريح في المصدر» (ما ورد مباشرة في الملف).
2. «استنتاج ديداكتيكي» (ما يمكن استخلاصه منطقيًا دون إضافة محتوى جديد).
3. «اقتراح ديداكتيكي» (تنظيم أو إجراء تقترحه لتحسين قابلية التطبيق ولم يرد صراحة).

==================================================
سادسًا: التدرج الصريح وفق TaRL
راعِ مبدأ التدرج الصريح في تحليل الأنشطة الرئيسية:
النمذجة ← الممارسة الموجهة ← الممارسة المستقلة.
أ. إذا كانت صريحة في المصدر، حافظ عليها واظهرها بوضوح.
ب. إذا كانت ضمنية ويمكن استنتاجها، حددها بوصفها «استنتاجًا ديداكتيكيًا».
ج. إذا لم تكن موجودة، فلا تخترعها.
د. يمكن اقتراح إعادة تنظيم النشاط وفق التدرج الصريح مع وسم ذلك بـ «اقتراح ديداكتيكي».

==================================================
سابعًا: خصوصية المادة
- اللغة العربية: افتتاح الحصة ← أنشطة قرائية ← أنشطة كتابية ← اختتام الحصة.
- الرياضيات: افتتاح الحصة / الحساب الذهني ← مجال الأعداد ← العمليات وحل المسائل ← الممارسة المستقلة ← اختتام الحصة.
"""

# ---------------------------------------------------------
# واجهة رفع الملفات والتشغيل
# ---------------------------------------------------------
uploaded_file = st.file_uploader("اختر ملف الحصة (PDF, PPTX, PNG, JPG):", type=["pdf", "pptx", "png", "jpg", "jpeg"])

if st.button("🚀 بدء التحليل الديداكتيكي", type="primary"):
    if not api_key:
        st.error("⚠️ يرجى إدخال مفتاح Gemini API في الشريط الجانبي لتشغيل التحليل.")
    elif not uploaded_file:
        st.warning("⚠️ يرجى تحميل ملف أولاً.")
    else:
        try:
            with st.spinner("جاري قراءة الملف وتحليله..."):
                client = genai.Client(api_key=api_key)
                
                # قراءة الملف كـ bytes
                file_bytes = uploaded_file.read()
                file_type = uploaded_file.type
                
                # إعداد المدخلات لـ Gemini
                uploaded_part = types.Part.from_bytes(
                    data=file_bytes,
                    mime_type=file_type if file_type else "application/pdf"
                )
                
                # إعداد آلية إعادة المحاولة التلقائية عند الضغط
                max_retries = 3
                response = None
                
                for attempt in range(max_retries):
                    try:
                        response = client.models.generate_content(
                            model="gemini-3.8-flash",
                            contents=[uploaded_part, SYSTEM_PROMPT]
                        )
                        break  # نجح الطلب، اخرج من الحلقة
                    except errors.APIError as e:
                        # في حالة وجود ضغط على الخادم (خطأ 503 أو UNAVAILABLE)
                        if (e.code == 503 or "UNAVAILABLE" in str(e)) and attempt < max_retries - 1:
                            wait_time = (attempt + 1) * 5
                            st.warning(f"⚠️ الخادم يواجه ضغطاً مؤقتاً. جاري إعادة المحاولة تلقائياً ({attempt + 1}/{max_retries}) بعد {wait_time} ثوانٍ...")
                            time.sleep(wait_time)
                        else:
                            raise e

                if response:
                    st.success("✅ اكتمل التحليل بنجاح!")
                    st.markdown("---")
                    st.markdown(response.text)

        except Exception as e:
            st.error(f"حدث خطأ أثناء معالجة الطلب: {str(e)}")
